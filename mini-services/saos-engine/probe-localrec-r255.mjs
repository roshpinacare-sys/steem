import { buildTx, signDigest, pubkeyFromSeed, wifDecode, STEEM_CHAIN_ID } from "./steemtx.mjs";
import { rpcCall } from "./measure.mjs";
import { Signature } from "@noble/secp256k1";
import * as fs from "node:fs";
import { createHash } from "node:crypto";
const cache = JSON.parse(fs.readFileSync("/home/z/my-project/.secrets/army-keys.json", "utf8"));
const g2 = cache.accounts.find((a) => a.name === "hcsoldier4").gens.find((g) => g.gen === "GEN-2");
const dgpo = (await rpcCall("condenser_api.get_dynamic_global_properties", [])).result;
const tx = buildTx({ ops: [["limit_order_cancel", { owner: "hcsoldier4", orderid: 999999999 }]], dgpo, wifs: [g2.activeWif] });
const sig = Buffer.from(tx.json.signatures[0], "hex");
const sigObj = Signature.fromCompact(sig.subarray(1)).addRecoveryBit(sig[0] - 27 - 4);
const rec = sigObj.recoverPublicKey(Buffer.from(tx.digestHex, "hex"));
console.log("local recovery :", Buffer.from(rec.toRawBytes(true)).toString("hex").slice(0, 20));
console.log("pubkeyFromSeed :", pubkeyFromSeed(wifDecode(String(g2.activeWif).trim())).slice(3, 23));
const s2 = signDigest(Buffer.from(tx.digestHex, "hex"), g2.activeWif);
console.log("deterministic resig identical:", s2.equals(sig));
