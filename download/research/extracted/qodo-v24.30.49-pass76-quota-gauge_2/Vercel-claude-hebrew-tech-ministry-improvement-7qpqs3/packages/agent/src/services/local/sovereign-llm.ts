/**
 * sovereign-llm.ts — the zero-dependency, fully-local intelligence layer.
 *
 * Two sovereign paths, neither of which touches a metered vendor API:
 *
 *   1. SIMULATION (`QODO_LLM_SIM=true`) — a deterministic, schema-perfect
 *      responder. It returns valid Architect / Coder / Reviewer / red-team /
 *      Cartographer JSON derived from the actual objective + prompt, so the
 *      REAL pipeline (every phase, gate, guard, checkpoint) runs end-to-end
 *      with no network, no credentials, and no external service. This is the
 *      guaranteed-offline core path used by `--eval`.
 *
 *   2. OLLAMA (`OLLAMA_BASE_URL`) — a genuinely intelligent but still
 *      sovereign path: a local Ollama server (OpenAI-compatible) on the
 *      owner's own machine. No data leaves the host. Optional, opt-in, and
 *      kept separate from the guaranteed-offline simulation core.
 *
 * The router (`aiRoute`) consults `isSimEnabled()` / `ollamaSpec()` BEFORE any
 * tier-0/1/2 logic. When neither is active the module is inert and the agent
 * behaves exactly as before.
 */
import type { RouterEnv } from "../ai-router.js";

// ---------------------------------------------------------------------------
// Activation
// ---------------------------------------------------------------------------

/** True when the deterministic sovereign simulator should answer every call. */
export function isSimEnabled(env: RouterEnv): boolean {
  return env.QODO_LLM_SIM === "true";
}

/**
 * True when the run is a sovereign LOCAL run (simulator or on-device Ollama).
 * Callers use this to skip optional, network-backed accelerators — remote
 * context enrichment, the Xenova embedder used by the semantic cache / hive /
 * skill vector store — so a `--eval` run is provably offline and never hangs
 * trying to download a model. The core delivery path is unaffected.
 */
export function isSovereignLocal(env: RouterEnv): boolean {
  return env.QODO_LLM_SIM === "true" || !!(env.OLLAMA_BASE_URL && env.OLLAMA_BASE_URL.trim());
}

/** Local Ollama base URL (e.g. http://localhost:11434), or undefined. */
export function ollamaBaseUrl(env: RouterEnv): string | undefined {
  const raw = env.OLLAMA_BASE_URL;
  return raw && raw.trim() ? raw.trim().replace(/\/+$/, "") : undefined;
}

/** Model id for the local Ollama path (default: a small, common local model). */
export function ollamaModel(env: RouterEnv): string {
  return env.OLLAMA_MODEL?.trim() || "llama3.1";
}

// ---------------------------------------------------------------------------
// Deterministic simulator
// ---------------------------------------------------------------------------

/** Synthetic token usage so cost accounting + telemetry look real (cost = $0). */
export interface SimUsage {
  prompt_tokens: number;
  completion_tokens: number;
  total_tokens: number;
}

export interface SimResult {
  /** The raw string the router returns to the caller (valid JSON or summary). */
  content: string;
  usage: SimUsage;
  /** A stable label so cost/telemetry attribute the call to the sovereign path. */
  model: string;
}

/** ~4 chars/token is the usual rough estimate; deterministic, no randomness. */
function estimateTokens(text: string): number {
  return Math.max(1, Math.ceil(text.length / 4));
}

/** A filesystem-safe slug derived from the objective, for demo file paths. */
function objectiveSlug(objective: string): string {
  const s = objective
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 40);
  return s || "objective";
}

/** Pull the objective out of an Architect/Coder prompt ("Objective: ..."). */
function extractObjective(prompt: string): string {
  const m = prompt.match(/Objective:\s*(.+)/);
  return (m?.[1] ?? "").trim() || "the requested change";
}

function buildPlan(prompt: string): string {
  const objective = extractObjective(prompt);
  const slug = objectiveSlug(objective);
  const targetFile = `src/${slug}.ts`;
  const testFile = `src/${slug}.test.ts`;
  return JSON.stringify({
    steps: [
      {
        id: "step-1",
        description: `Implement ${objective} in a single, well-scoped module.`,
        files: [targetFile],
      },
      {
        id: "step-2",
        description: `Add focused unit tests covering the happy path and one edge case for ${objective}.`,
        files: [testFile],
      },
    ],
    risk: "low",
    prefetch: [targetFile],
  });
}

function buildPatch(path: string, prompt: string): string {
  const objective = extractObjective(prompt);
  // The coder is called with the target file path as the router `path` arg.
  const filePath = path && path !== "coder" ? path : "src/feature.ts";
  const symbol = objectiveSlug(objective).replace(/-([a-z])/g, (_, c) => c.toUpperCase()) || "feature";
  const content =
    `// Auto-generated by the Qodo sovereign simulator to satisfy: ${objective}\n` +
    `export function ${symbol}(input: string): string {\n` +
    `  if (!input) throw new Error("input is required");\n` +
    `  return input.trim();\n` +
    `}\n`;
  const diff =
    `--- /dev/null\n+++ b/${filePath}\n@@ -0,0 +${content.split("\n").length} @@\n` +
    content
      .split("\n")
      .map((l) => `+${l}`)
      .join("\n");
  return JSON.stringify({ diff, files: [{ path: filePath, content }] });
}

function buildReview(): string {
  return JSON.stringify({
    summary:
      "Sovereign review: the change is small, self-contained, and guards its single input. " +
      "No secrets, no path escapes, no blast-radius concerns. Approved.",
    annotations: [],
  });
}

function buildRedTeam(): string {
  // No high-severity findings → the gate proceeds cleanly.
  return JSON.stringify({ findings: [] });
}

function buildMutation(): string {
  return "You are a sub-agent. Return ONLY valid JSON that matches your schema. No prose, no code fences.";
}

function buildSummary(path: string): string {
  return `Sovereign summary of ${path}: a focused module exposing a small public API; low coupling to the rest of the tree.`;
}

/**
 * Produce a deterministic, schema-valid response for a router call. The `path`
 * (and, for the coder/cartographer collision, the prompt shape) select the
 * response contract — mirroring how the real agents key off their own paths.
 */
export function simulateResponse(path: string, prompt: string): SimResult {
  let content: string;
  if (path === "plan.json") {
    content = buildPlan(prompt);
  } else if (path === "review.json") {
    content = buildReview();
  } else if (path === "red-team-pass") {
    content = buildRedTeam();
  } else if (path === "mutation.json") {
    content = buildMutation();
  } else if (/^Summarize the following code file/.test(prompt)) {
    // Cartographer shares the "real file path" shape with the coder; the
    // prompt preamble is the reliable discriminator.
    content = buildSummary(path);
  } else {
    content = buildPatch(path, prompt);
  }
  return {
    content,
    usage: {
      prompt_tokens: estimateTokens(prompt),
      completion_tokens: estimateTokens(content),
      total_tokens: estimateTokens(prompt) + estimateTokens(content),
    },
    model: "qodo-sovereign-sim",
  };
}
