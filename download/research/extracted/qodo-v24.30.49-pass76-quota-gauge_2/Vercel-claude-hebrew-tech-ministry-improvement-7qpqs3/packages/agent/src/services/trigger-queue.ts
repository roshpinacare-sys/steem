/**
 * trigger-queue.ts — the resume-loop queue adapter (ADR-005).
 *
 * `webhook-receiver.js` LPUSHes pipeline triggers (`/qodo proceed`, PR events,
 * check-suite failures) onto the canonical Redis list `qodo:trigger:queue`
 * (ADR-003). Until now nothing drained it — the resume loop was open. This
 * adapter is the consumption seam: a narrow interface with a Redis-backed
 * production implementation and an in-memory implementation for tests, per
 * ADR-001 (narrow interfaces at the point of consumption, no `ports/` layer).
 *
 * Reliability model (ADR-005 §"Queue reliability model", NEXT-STEP IR5):
 *   - pop() atomically LMOVEs queue → processing, so a consumer crash never
 *     silently drops a trigger (a plain BRPOP is destructive/at-most-once).
 *   - The dispatched pipeline run writes a durable ack key
 *     (`qodo:trigger:ack:<taskId>`) at its first checkpoint.
 *   - reap() reconciles the processing list against those ack keys: acked
 *     items are completed (removed), stale un-acked items are requeued with an
 *     incremented attempt count, and items past the attempt cap go to the
 *     dead-letter list. This yields: no loss on crash-before-ack, no duplicate
 *     run on crash-after-ack, poison messages dead-lettered after N attempts.
 */

export const TRIGGER_QUEUE_KEY = "qodo:trigger:queue";
export const TRIGGER_PROCESSING_KEY = "qodo:trigger:processing";
export const TRIGGER_DEAD_KEY = "qodo:trigger:dead";
export const TRIGGER_ACK_PREFIX = "qodo:trigger:ack:";

/** 24h — long enough that a slow pipeline's ack survives until reconciled. */
export const ACK_TTL_SEC = 24 * 60 * 60;

export interface TriggerTask {
  /** Unique id; generated by push() when absent. */
  taskId: string;
  owner: string;
  repo: string;
  prNumber?: number;
  prSha?: string;
  objective?: string;
  /** Provenance, e.g. "webhook:issue_comment:proceed". */
  trigger: string;
  defaultBranch?: string;
  /** Delivery attempts so far; incremented by the reaper on requeue. */
  attempts: number;
  /** ms epoch: enqueue time, refreshed on pop-into-processing and on requeue. */
  enqueuedAt: number;
}

export interface ReapResult {
  completed: string[]; // taskIds acked and removed from processing
  requeued: string[]; // taskIds moved back to the queue for another attempt
  dead: string[]; // taskIds sent to the dead-letter list
}

export interface ReapOptions {
  /** A processing item older than this (ms) with no ack is considered stale. */
  staleMs: number;
  /** Attempts before a stale item is dead-lettered instead of requeued. */
  maxAttempts: number;
}

export interface TriggerQueue {
  /** Enqueue a trigger; returns the normalized task actually stored. */
  push(task: Partial<TriggerTask> & Pick<TriggerTask, "owner" | "repo" | "trigger">): Promise<TriggerTask>;
  /** Atomically move the oldest queued task into the processing list. */
  pop(): Promise<TriggerTask | null>;
  /** Record the durable ack for a task (called by the resumed pipeline run). */
  ack(taskId: string): Promise<void>;
  /** True once ack() has been recorded for the task. */
  isAcked(taskId: string): Promise<boolean>;
  /** Remove a specific in-flight task from the processing list. */
  complete(task: TriggerTask): Promise<void>;
  /** Reconcile the processing list against acks + staleness. */
  reap(opts: ReapOptions): Promise<ReapResult>;
  /** Introspection for telemetry/tests. */
  depth(): Promise<{ queued: number; processing: number; dead: number }>;
}

// ── Normalization ───────────────────────────────────────────────────────────

let taskCounter = 0;

function generateTaskId(): string {
  taskCounter = (taskCounter + 1) % 1_000_000;
  return `trig-${Date.now().toString(36)}-${taskCounter.toString(36)}-${Math.random().toString(36).slice(2, 8)}`;
}

/**
 * Build a task with a stable key order so JSON.stringify is deterministic —
 * the processing list is reconciled by exact-string LREM, so the serialized
 * form must be identical every time we (re)write the same task.
 */
function normalizeTask(
  input: Partial<TriggerTask> & Pick<TriggerTask, "owner" | "repo" | "trigger">,
  now: number,
): TriggerTask {
  return {
    taskId: input.taskId || generateTaskId(),
    owner: input.owner,
    repo: input.repo,
    prNumber: input.prNumber,
    prSha: input.prSha,
    objective: input.objective,
    trigger: input.trigger,
    defaultBranch: input.defaultBranch,
    attempts: input.attempts ?? 0,
    enqueuedAt: input.enqueuedAt ?? now,
  };
}

/** Serialize with a fixed key order (see normalizeTask). */
function serializeTask(task: TriggerTask): string {
  return JSON.stringify(task);
}

/** Tolerant parse: accepts adapter-shaped tasks and legacy webhook payloads. */
function parseTask(raw: string, now: number): TriggerTask | null {
  let obj: Record<string, unknown>;
  try {
    obj = JSON.parse(raw) as Record<string, unknown>;
  } catch {
    return null;
  }
  // Legacy webhook items were `{ owner, repo, prNumber, trigger }` with no
  // adapter metadata — normalize them so the reaper can still track them.
  const owner = typeof obj.owner === "string" ? obj.owner : "";
  const repo = typeof obj.repo === "string" ? obj.repo : "";
  const trigger = typeof obj.trigger === "string" ? obj.trigger : "unknown";
  if (!owner || !repo) return null;
  return normalizeTask(
    {
      taskId: typeof obj.taskId === "string" ? obj.taskId : undefined,
      owner,
      repo,
      prNumber: typeof obj.prNumber === "number" ? obj.prNumber : undefined,
      prSha: typeof obj.prSha === "string" ? obj.prSha : undefined,
      objective: typeof obj.objective === "string" ? obj.objective : undefined,
      trigger,
      defaultBranch: typeof obj.defaultBranch === "string" ? obj.defaultBranch : undefined,
      attempts: typeof obj.attempts === "number" ? obj.attempts : 0,
      enqueuedAt: typeof obj.enqueuedAt === "number" ? obj.enqueuedAt : now,
    },
    now,
  );
}

// ── Redis implementation ─────────────────────────────────────────────────────

/**
 * The narrow slice of RedisState the adapter needs. Declaring it here (rather
 * than importing the whole RedisState type) keeps the seam swappable and the
 * unit under test small — ADR-001's "interface at the consumption point".
 */
export interface RedisListOps {
  lpush(key: string, value: string): Promise<void>;
  lmove(source: string, dest: string, from: "LEFT" | "RIGHT", to: "LEFT" | "RIGHT"): Promise<string | null>;
  lrem(key: string, count: number, value: string): Promise<number>;
  lrange(key: string, start: number, stop: number): Promise<string[]>;
  llen(key: string): Promise<number>;
  exists(key: string): Promise<boolean>;
  setWithTTL(key: string, value: string, ttlSec: number): Promise<void>;
}

export class RedisTriggerQueue implements TriggerQueue {
  constructor(
    private readonly redis: RedisListOps,
    private readonly now: () => number = Date.now,
  ) {}
  // NOTE: this class is store-agnostic — it consumes `RedisListOps`, a narrow
  // 7-method durable-store contract, NOT Redis directly. The sovereign
  // `FileDurableStore` (sovereign-store.ts) satisfies the same contract, so the
  // resume loop runs with zero external services. `StoreTriggerQueue` below is
  // the substrate-neutral name; `RedisTriggerQueue` is kept for compatibility.

  async push(input: Partial<TriggerTask> & Pick<TriggerTask, "owner" | "repo" | "trigger">): Promise<TriggerTask> {
    const task = normalizeTask(input, this.now());
    await this.redis.lpush(TRIGGER_QUEUE_KEY, serializeTask(task));
    return task;
  }

  async pop(): Promise<TriggerTask | null> {
    // Oldest item sits at the right (producers LPUSH to the left) → RIGHT→LEFT
    // is FIFO. The move to the processing list is atomic, so a crash between
    // "removed from queue" and "handed to the pipeline" cannot lose the item.
    const raw = await this.redis.lmove(TRIGGER_QUEUE_KEY, TRIGGER_PROCESSING_KEY, "RIGHT", "LEFT");
    if (raw === null) return null;
    const task = parseTask(raw, this.now());
    if (!task) {
      // Unparseable — drop it out of processing so it can't wedge the reaper.
      await this.redis.lrem(TRIGGER_PROCESSING_KEY, 1, raw);
      return null;
    }
    // Stamp processing-entry time so reap() measures staleness from the pop,
    // and rewrite the processing entry to the canonical serialization.
    task.enqueuedAt = this.now();
    const canonical = serializeTask(task);
    if (canonical !== raw) {
      await this.redis.lrem(TRIGGER_PROCESSING_KEY, 1, raw);
      await this.redis.lpush(TRIGGER_PROCESSING_KEY, canonical);
    }
    return task;
  }

  async ack(taskId: string): Promise<void> {
    await this.redis.setWithTTL(`${TRIGGER_ACK_PREFIX}${taskId}`, String(this.now()), ACK_TTL_SEC);
  }

  async isAcked(taskId: string): Promise<boolean> {
    return this.redis.exists(`${TRIGGER_ACK_PREFIX}${taskId}`);
  }

  async complete(task: TriggerTask): Promise<void> {
    await this.redis.lrem(TRIGGER_PROCESSING_KEY, 1, serializeTask(task));
  }

  async reap({ staleMs, maxAttempts }: ReapOptions): Promise<ReapResult> {
    const result: ReapResult = { completed: [], requeued: [], dead: [] };
    const items = await this.redis.lrange(TRIGGER_PROCESSING_KEY, 0, -1);
    const now = this.now();
    for (const raw of items) {
      const task = parseTask(raw, now);
      if (!task) {
        await this.redis.lrem(TRIGGER_PROCESSING_KEY, 1, raw);
        continue;
      }
      if (await this.isAcked(task.taskId)) {
        await this.redis.lrem(TRIGGER_PROCESSING_KEY, 1, raw);
        result.completed.push(task.taskId);
        continue;
      }
      if (now - task.enqueuedAt <= staleMs) continue; // still in flight
      await this.redis.lrem(TRIGGER_PROCESSING_KEY, 1, raw);
      if (task.attempts + 1 >= maxAttempts) {
        await this.redis.lpush(TRIGGER_DEAD_KEY, raw);
        result.dead.push(task.taskId);
      } else {
        const requeued = { ...task, attempts: task.attempts + 1, enqueuedAt: now };
        await this.redis.lpush(TRIGGER_QUEUE_KEY, serializeTask(requeued));
        result.requeued.push(task.taskId);
      }
    }
    return result;
  }

  async depth(): Promise<{ queued: number; processing: number; dead: number }> {
    const [queued, processing, dead] = await Promise.all([
      this.redis.llen(TRIGGER_QUEUE_KEY),
      this.redis.llen(TRIGGER_PROCESSING_KEY),
      this.redis.llen(TRIGGER_DEAD_KEY),
    ]);
    return { queued, processing, dead };
  }
}

/**
 * Substrate-neutral alias. The queue works over any `RedisListOps` — Redis, the
 * sovereign `FileDurableStore`, or a future Git-ref store — so prefer this name
 * at call sites that aren't specifically Redis.
 */
export { RedisTriggerQueue as StoreTriggerQueue };

// ── In-memory implementation (tests, local dev, offline bootstraps) ──────────

export class InMemoryTriggerQueue implements TriggerQueue {
  private queue: string[] = []; // newest at index 0 (LPUSH semantics)
  private processing: string[] = [];
  private dead: string[] = [];
  private acks = new Set<string>();

  /** Injectable clock so tests can advance time deterministically. */
  constructor(private now: () => number = Date.now) {}

  setClock(fn: () => number): void {
    this.now = fn;
  }

  async push(input: Partial<TriggerTask> & Pick<TriggerTask, "owner" | "repo" | "trigger">): Promise<TriggerTask> {
    const task = normalizeTask(input, this.now());
    this.queue.unshift(serializeTask(task));
    return task;
  }

  async pop(): Promise<TriggerTask | null> {
    const raw = this.queue.pop() ?? null; // RIGHT (oldest) → FIFO
    if (raw === null) return null;
    const task = parseTask(raw, this.now());
    if (!task) return null;
    task.enqueuedAt = this.now();
    this.processing.unshift(serializeTask(task));
    return task;
  }

  async ack(taskId: string): Promise<void> {
    this.acks.add(taskId);
  }

  async isAcked(taskId: string): Promise<boolean> {
    return this.acks.has(taskId);
  }

  async complete(task: TriggerTask): Promise<void> {
    const raw = serializeTask(task);
    const i = this.processing.indexOf(raw);
    if (i >= 0) this.processing.splice(i, 1);
  }

  async reap({ staleMs, maxAttempts }: ReapOptions): Promise<ReapResult> {
    const result: ReapResult = { completed: [], requeued: [], dead: [] };
    const now = this.now();
    const survivors: string[] = [];
    for (const raw of this.processing) {
      const task = parseTask(raw, now);
      if (!task) continue;
      if (this.acks.has(task.taskId)) {
        result.completed.push(task.taskId);
        continue;
      }
      if (now - task.enqueuedAt <= staleMs) {
        survivors.push(raw);
        continue;
      }
      if (task.attempts + 1 >= maxAttempts) {
        this.dead.unshift(raw);
        result.dead.push(task.taskId);
      } else {
        this.queue.unshift(serializeTask({ ...task, attempts: task.attempts + 1, enqueuedAt: now }));
        result.requeued.push(task.taskId);
      }
    }
    this.processing = survivors;
    return result;
  }

  async depth(): Promise<{ queued: number; processing: number; dead: number }> {
    return { queued: this.queue.length, processing: this.processing.length, dead: this.dead.length };
  }
}
