import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
const args=Object.fromEntries(process.argv.slice(2).map((v,i,a)=>v.startsWith("--")?[v.slice(2),a[i+1]]:null).filter(Boolean));
if(!args.zip||!args.evidence||!args.output) throw new Error("usage: --zip <path> --evidence <path> --output <path>");
for(const p of [args.zip,args.evidence]) if(!existsSync(resolve(p))) throw new Error(`missing:${p}`);
const hash=createHash("sha256").update(readFileSync(resolve(args.zip))).digest("hex");
const evidence=JSON.parse(readFileSync(resolve(args.evidence),"utf8"));
const reasons=[];
if(evidence.releaseCandidateHash && evidence.releaseCandidateHash!==hash) reasons.push("release_hash_mismatch");
for(const [id,gate] of Object.entries(evidence.gates??{})) if(gate.state!=="pass") reasons.push(`gate_not_passed:${id}:${gate.state}`);
const verifier=args.verifier??"independent-release-verifier"; const builder=args.builder??"titai-builder";
if(verifier===builder) reasons.push("verification_identity_collision");
const result={schemaVersion:1,verifiedAt:new Date().toISOString(),zipSha256:hash,builderIdentity:builder,verifierIdentity:verifier,status:reasons.length?"rejected":"accepted",releaseClassification:reasons.length?"DEVELOPMENT ONLY":"CONTROLLED INTERNAL PILOT",reasons};
writeFileSync(resolve(args.output),JSON.stringify(result,null,2)+"\n");
console.log(`Independent candidate verification: ${result.status}; ${reasons.length} reason(s).`);
if(reasons.length) process.exitCode=2;
