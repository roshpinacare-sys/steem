"""
saarthi_sva_generator.py
========================

Saarthi-level SystemVerilog Assertion (SVA) generator.

Generates SVA assertions from declarative safety invariants for use in
RTL and I2C formal verification.  The generator takes a Z3-style
invariant and emits a synthesizable SVA module that can be loaded
into a hardware model checker (JasperGold, VC Formal, etc.).

Adm linkage:
  - The generated SVAs enforce Adm_thermal (Chapter 7.4) at the RTL level.
  - The Saarthi agent uses these SVAs as the `formal` validator type
    in the SQA quorum (Chapter 4.2).
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional


# ---------------------------------------------------------------------------
# 1. Invariant model
# ---------------------------------------------------------------------------

@dataclass
class SVAInvariant:
    """A declarative safety invariant to be compiled into SVA."""
    name: str
    description: str
    antecedent: str    # SystemVerilog expression (boolean)
    consequent: str    # SystemVerilog expression (boolean)
    temporal: str = "immediate"   # "immediate" | "always" | "eventually"


