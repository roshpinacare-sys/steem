# ---------------------------------------------------------------------------
# 3. SVA generator
# ---------------------------------------------------------------------------

class SVAGenerator:
    """Generates SystemVerilog Assertions from declarative invariants."""

    def __init__(self, module_name: str = "srs_sva_assertions") -> None:
        self.module_name = module_name

    def generate(self, invariants: List[SVAInvariant]) -> str:
        """Generate a complete SVA module from a list of invariants."""
        lines: List[str] = []
        lines.append(f"// Auto-generated by saarthi_sva_generator.py")
        lines.append(f"// Module: {self.module_name}")
        lines.append(f"// Invariants: {len(invariants)}")
        lines.append("")
        lines.append(f"module {self.module_name} (")
        lines.append("    // Inputs (assumed connected to the DUT's signals)")
        lines.append("    input  logic [31:0] theta_island,")
        lines.append("    input  logic [31:0] F_island,")
        lines.append("    input  logic [31:0] THETA_HIGH,")
        lines.append("    input  logic [31:0] F_HIGH,")
        lines.append("    input  logic        current_over_max,")
        lines.append("    input  logic        over_current_detector,")
        lines.append("    input  logic        i2c_start, i2c_address_phase,")
        lines.append("    input  logic        i2c_byte_complete, i2c_ack_count,")
        lines.append("    input  logic        i2c_stop, i2c_is_master,")
        lines.append("    input  logic [31:0] theta_apu, theta_rpu, theta_fpga, theta_nisq,")
        lines.append("    input  logic        clk, rst_n")
        lines.append(");")
        lines.append("")
        lines.append("    // Real-number approximations (fixed-point)")
        lines.append("    real theta_island_r, F_island_r, THETA_HIGH_r, F_HIGH_r;")
        lines.append("    real theta_apu_r, theta_rpu_r, theta_fpga_r, theta_nisq_r;")
        lines.append("    real current_r, MAX_RATED_r;")
        lines.append("")
        lines.append("    always_comb begin")
        lines.append("        theta_island_r = $bitstoreal(theta_island);")
        lines.append("        F_island_r     = $bitstoreal(F_island);")
        lines.append("        THETA_HIGH_r   = $bitstoreal(THETA_HIGH);")
        lines.append("        F_HIGH_r       = $bitstoreal(F_HIGH);")
        lines.append("        theta_apu_r    = $bitstoreal(theta_apu);")
        lines.append("        theta_rpu_r    = $bitstoreal(theta_rpu);")
        lines.append("        theta_fpga_r   = $bitstoreal(theta_fpga);")
        lines.append("        theta_nisq_r   = $bitstoreal(theta_nisq);")
        lines.append("    end")
        lines.append("")
        lines.append("    // === Generated Assertions ===")
        lines.append("")

        for inv in invariants:
            lines.append(f"    // {inv.name}: {inv.description}")
            if inv.temporal == "always":
                lines.append(f"    property {inv.name}_p;")
                lines.append(f"        @(posedge clk) disable iff (!rst_n)")
                lines.append(f"        ({inv.antecedent}) |-> ({inv.consequent});")
                lines.append(f"    endproperty")
                lines.append(f"    assert_{inv.name}: assert property ({inv.name}_p)")
                lines.append(f"        else $error(\"{inv.name} violated\");")
            elif inv.temporal == "eventually":
                lines.append(f"    property {inv.name}_p;")
                lines.append(f"        @(posedge clk) disable iff (!rst_n)")
                lines.append(f"        ({inv.antecedent}) |-> ##[1:$] ({inv.consequent});")
                lines.append(f"    endproperty")
                lines.append(f"    assert_{inv.name}: assert property ({inv.name}_p)")
                lines.append(f"        else $error(\"{inv.name} violated\");")
            else:  # immediate
                lines.append(f"    {inv.name}_immediate: assert final ({inv.antecedent} -> {inv.consequent})")
                lines.append(f"        else $error(\"{inv.name} violated\");")
            lines.append("")

        lines.append("endmodule")
        return "\n".join(lines)

    def generate_coverage(self, invariants: List[SVAInvariant]) -> str:
        """Generate cover properties for the invariants (for verification completeness)."""
        lines: List[str] = []
        lines.append(f"// Coverage properties for {self.module_name}")
        lines.append("")
        for inv in invariants:
            lines.append(f"    cover_{inv.name}: cover property ({inv.antecedent});")
        return "\n".join(lines)


